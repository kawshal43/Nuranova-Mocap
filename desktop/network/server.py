def enumerate_lan_ipv4_addresses() -> List[Tuple[str, str]]:
    """Return sorted list of (adapter_label, ipv4_str) prioritizing real Wi-Fi/Ethernet LAN interfaces."""
    candidates: List[Tuple[int, str, str]] = []
    seen_ips: set[str] = set()

    # Preferred: ifaddr (already bundled via zeroconf)
    try:
        import ifaddr

        for adapter in ifaddr.get_adapters():
            nice = str(adapter.nice_name or adapter.name or "Adapter")
            low = nice.lower()
            is_virtual = any(h in low for h in _VIRTUAL_ADAPTER_HINTS)
            is_wifi_or_eth = any(k in low for k in ("wi-fi", "wifi", "wireless", "wlan", "ethernet", "lan", "realtek", "intel"))
            for ip_obj in adapter.ips:
                if not ip_obj.is_IPv4:
                    continue
                ip_str = str(ip_obj.ip)
                if ip_str in seen_ips:
                    continue
                try:
                    addr = ipaddress.IPv4Address(ip_str)
                except ValueError:
                    continue
                if addr.is_loopback or addr.is_link_local or addr.is_unspecified:
                    continue
                seen_ips.add(ip_str)
                # Lower priority score = ranked first
                prio = 2
                if not is_virtual and addr.is_private:
                    prio = 0 if is_wifi_or_eth else 1
                elif is_virtual:
                    prio = 3
                candidates.append((prio, nice, ip_str))
    except Exception:
        pass

    # Fallback via outbound UDP socket route
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("192.0.2.1", 80))
        ip_str = s.getsockname()[0]
        s.close()
        if ip_str not in seen_ips and not ip_str.startswith("127.") and not ip_str.startswith("169.254."):
            seen_ips.add(ip_str)
            candidates.append((0, "Default Route", ip_str))
    except Exception:
        pass

    candidates.sort(key=lambda item: (item[0], item[1], item[2]))
    return [(label, ip) for _, label, ip in candidates]


def _compute_broadcast_targets(ips: List[str]) -> List[str]:
    targets = ["255.255.255.255"]
    for ip_str in ips:
        parts = ip_str.split(".")
        if len(parts) == 4:
            bcast = f"{parts[0]}.{parts[1]}.{parts[2]}.255"
            if bcast not in targets:
                targets.append(bcast)
    return targets


def check_windows_firewall(port: int = DEFAULT_SERVER_PORT, udp_port: int = UDP_DISCOVERY_PORT) -> Dict[str, Any]:
    """Inspect Windows Firewall readiness for LAN phone connections (fast, non-blocking check)."""
    if platform.system() != "Windows":
        return {"ok": True, "platform": platform.system(), "summary": "Non-Windows platform (no Windows Firewall check needed)."}

    ps_script = (
        "$prof = (Get-NetConnectionProfile -ErrorAction SilentlyContinue | Select-Object -First 1).NetworkCategory; "
        "$tcpOk = [bool](Get-NetFirewallPortFilter -ErrorAction SilentlyContinue | Where-Object { $_.LocalPort -eq '" + str(port) + "' -and $_.Protocol -eq 'TCP' } | "
        "ForEach-Object { Get-NetFirewallRule -AssociatedNetFirewallPortFilter $_ -ErrorAction SilentlyContinue } | "
        "Where-Object { $_.Enabled -eq 'True' -and $_.Direction -eq 'Inbound' -and $_.Action -eq 'Allow' }); "
        "$udpOk = [bool](Get-NetFirewallPortFilter -ErrorAction SilentlyContinue | Where-Object { $_.LocalPort -eq '" + str(udp_port) + "' -and $_.Protocol -eq 'UDP' } | "
        "ForEach-Object { Get-NetFirewallRule -AssociatedNetFirewallPortFilter $_ -ErrorAction SilentlyContinue } | "
        "Where-Object { $_.Enabled -eq 'True' -and $_.Direction -eq 'Inbound' -and $_.Action -eq 'Allow' }); "
        "$blocks = @(Get-NetFirewallRule -DisplayName '*Python*' -ErrorAction SilentlyContinue | Where-Object { $_.Enabled -eq 'True' -and $_.Direction -eq 'Inbound' -and $_.Action -eq 'Block' } | Select-Object -ExpandProperty DisplayName); "
        "@{ profile = [string]$prof; has_tcp_rule = $tcpOk; has_udp_rule = $udpOk; blocking_python_rules = $blocks.Count } | ConvertTo-Json -Compress"
    )
    try:
        out = subprocess.check_output(
            ["powershell", "-NoProfile", "-Command", ps_script],
            stderr=subprocess.DEVNULL,
            text=True,
            timeout=5,
        ).strip()
        data = json.loads(out) if out else {}
        has_tcp = bool(data.get("has_tcp_rule", False))
        has_udp = bool(data.get("has_udp_rule", False))
        blocks = int(data.get("blocking_python_rules", 0))
        net_prof = str(data.get("profile") or "Unknown")
        ok = has_tcp and has_udp
        if ok:
            summary = f"Firewall Ready ({net_prof} network, TCP {port} & UDP {udp_port} allowed)."
        else:
            missing = []
            if not has_tcp:
                missing.append(f"TCP {port}")
            if not has_udp:
                missing.append(f"UDP {udp_port}")
            summary = f"Windows Firewall may block phones ({net_prof} network; missing Inbound Allow for {', '.join(missing)})."
        return {
            "ok": ok,
            "profile": net_prof,
            "has_tcp_rule": has_tcp,
            "has_udp_rule": has_udp,
            "blocking_python_rules": blocks,
            "summary": summary,
        }
    except Exception as exc:
        return {
            "ok": False,
            "profile": "Unknown",
            "has_tcp_rule": False,
            "has_udp_rule": False,
            "blocking_python_rules": 0,
            "summary": f"Could not inspect Windows Firewall ({exc}). Ensure TCP {port} & UDP {udp_port} are allowed.",
        }


def build_firewall_fix_commands(port: int = DEFAULT_SERVER_PORT, udp_port: int = UDP_DISCOVERY_PORT) -> str:
    """Return exact Administrator PowerShell commands to open Studio LAN ports in Windows Firewall."""
    py_exe = str(Path(sys.executable).resolve())
    base_py = str((Path(sys.base_prefix) / "python.exe").resolve())
    return (
        f'netsh advfirewall firewall delete rule name="Nuranova Mocap Studio LAN (TCP {port})" 2>$null; '
        f'netsh advfirewall firewall delete rule name="Nuranova Mocap Studio Discovery (UDP {udp_port})" 2>$null; '
        f'netsh advfirewall firewall add rule name="Nuranova Mocap Studio LAN (TCP {port})" dir=in action=allow protocol=TCP localport={port} profile=private,domain,public; '
        f'netsh advfirewall firewall add rule name="Nuranova Mocap Studio Discovery (UDP {udp_port})" dir=in action=allow protocol=UDP localport={udp_port} profile=private,domain,public; '
        f'netsh advfirewall firewall add rule name="Nuranova Mocap Python" dir=in action=allow program="{py_exe}" profile=private,domain,public; '
        f'netsh advfirewall firewall add rule name="Nuranova Mocap Python Base" dir=in action=allow program="{base_py}" profile=private,domain,public'
    )


def request_elevated_firewall_fix(port: int = DEFAULT_SERVER_PORT, udp_port: int = UDP_DISCOVERY_PORT) -> Tuple[bool, str]:
    """Trigger Windows UAC elevation prompt to add Nuranova LAN inbound firewall rules."""
    if platform.system() != "Windows":
        return False, "Automated firewall configuration is Windows-only."
    cmds = build_firewall_fix_commands(port, udp_port)
    # Encode as Base64 UTF-16LE for safe passing through Start-Process -Verb RunAs
    import base64

    encoded = base64.b64encode(cmds.encode("utf-16le")).decode("ascii")
    try:
        subprocess.run(
            [
                "powershell",
                "-NoProfile",
                "-Command",
                f"Start-Process powershell -Verb RunAs -Wait -WindowStyle Hidden -ArgumentList '-NoProfile','-EncodedCommand','{encoded}'",
            ],
            check=True,
            timeout=30,
        )
        return True, f"Windows Firewall rules added for TCP {port} and UDP {udp_port}."
    except Exception as exc:
        return False, f"Firewall setup was cancelled or failed: {exc}"


