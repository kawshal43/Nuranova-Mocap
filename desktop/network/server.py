"""Local FastAPI + WebSocket + mDNS Zeroconf Studio Server for Android Cameras & Blender Bridge.

Security:
- Local LAN only (no external cloud relays or uploads).
- Pairing requires an active single-use 6-digit PIN generated by Mocap Studio.
- All camera control, telemetry, sync, and file transfer endpoints require Bearer token authentication.
- Filenames are strictly sanitized against path traversal.
- Resumable chunked uploads verify SHA-256 checksums before authorizing local phone copy deletion.
"""

from __future__ import annotations

import hashlib
import json
import socket
import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from fastapi import Depends, FastAPI, Header, HTTPException, Request, WebSocket, WebSocketDisconnect
from fastapi.responses import JSONResponse

from desktop.camera_manager.manager import CameraManager, ManagedCameraRecord
from desktop.synchronization.sync_engine import ClockSyncSample
from shared_protocol.protocol import (
    DEFAULT_SERVER_PORT,
    MDNS_SERVICE_TYPE,
    PROTOCOL_VERSION,
    BridgeStatusPayload,
    CameraConnectionState,
    ClockSyncRequest,
    ClockSyncResponse,
    DeviceTelemetry,
    PairRequest,
    PairResponse,
    ScheduleRecordCommand,
    StopRecordCommand,
    TransferInitRequest,
    TransferInitResponse,
    TransferStatusResponse,
)


@dataclass
class TransferSlot:
    transfer_id: str
    device_id: str
    session_id: str
    take_id: str
    file_kind: str
    dest_path: Path
    total_size_bytes: int
    expected_sha256: str
    received_bytes: int = 0
    verified: bool = False
    computed_sha256: Optional[str] = None


class StudioNetworkServer:
    """Encapsulates the FastAPI app, active WebSocket connections, resumable transfers, and mDNS beacon."""

    def __init__(
        self,
        camera_manager: CameraManager,
        storage_root: str | Path,
        studio_name: str = "Nuranova Mocap Studio",
        port: int = DEFAULT_SERVER_PORT,
    ) -> None:
        self.camera_manager = camera_manager
        self.storage_root = Path(storage_root)
        self.storage_root.mkdir(parents=True, exist_ok=True)
        self.studio_name = studio_name
        self.port = port

        self._ws_clients: Dict[str, WebSocket] = {}
        self._transfers: Dict[str, TransferSlot] = {}
        self._transfer_lookup: Dict[Tuple[str, str, str], str] = {}  # (device_id, take_id, filename) -> transfer_id
        self._zeroconf = None
        self._zc_info = None
        self.bridge_project_name: Optional[str] = None
        self.bridge_project_path: Optional[str] = None
        self.bridge_takes: Dict[str, Path] = {}  # take_id -> blender_json_path

        self.app = self._build_app()

    def set_storage_root(self, new_root: str | Path) -> None:
        self.storage_root = Path(new_root)
        self.storage_root.mkdir(parents=True, exist_ok=True)

    def register_bridge_take(self, take_id: str, blender_json_path: Path) -> None:
        self.bridge_takes[take_id] = Path(blender_json_path)

    def start_mdns_advertisement(self, bind_ip: Optional[str] = None) -> bool:
        """Advertise `_nuranova-mocap._tcp.local.` on the local network so Android phones auto-discover Studio."""
        try:
            from zeroconf import ServiceInfo, Zeroconf

            ip = bind_ip or self._detect_lan_ip()
            self._zeroconf = Zeroconf()
            self._zc_info = ServiceInfo(
                MDNS_SERVICE_TYPE,
                f"{self.studio_name}.{MDNS_SERVICE_TYPE}",
                addresses=[socket.inet_aton(ip)],
                port=self.port,
                properties={
                    b"protocol_version": PROTOCOL_VERSION.encode("utf-8"),
                    b"studio_name": self.studio_name.encode("utf-8"),
                },
            )
            self._zeroconf.register_service(self._zc_info)
            return True
        except Exception:
            return False

    def stop_mdns_advertisement(self) -> None:
        if self._zeroconf is not None:
            try:
                if self._zc_info is not None:
                    self._zeroconf.unregister_service(self._zc_info)
                self._zeroconf.close()
            except Exception:
                pass
            self._zeroconf = None
            self._zc_info = None

    @staticmethod
    def _detect_lan_ip() -> str:
        try:
            s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            s.connect(("8.8.8.8", 80))
            ip = s.getsockname()[0]
            s.close()
            return ip
        except Exception:
            return "127.0.0.1"

    async def broadcast_schedule_record(
        self,
        session_id: str,
        take_id: str,
        lead_time_s: float = 1.5,
        flash_sync_pulse: bool = False,
        audio_clap_cue: bool = True,
    ) -> Dict[str, Any]:
        """Schedule synchronized recording across all enabled/connected active cameras."""
        ok, msg = self.camera_manager.can_record_multi_view()
        if not ok:
            raise RuntimeError(msg)

        target_studio_ns = time.monotonic_ns() + int(lead_time_s * 1e9)
        dispatched: List[str] = []
        errors: Dict[str, str] = {}

        for cam in self.camera_manager.get_active_body_cameras():
            dev_start_ns = (
                int(round(cam.clock_model.studio_to_device_ns(target_studio_ns)))
                if cam.clock_model is not None
                else target_studio_ns
            )
            cmd = ScheduleRecordCommand(
                session_id=session_id,
                take_id=take_id,
                scheduled_start_studio_ns=target_studio_ns,
                scheduled_start_device_ns=dev_start_ns,
                config=cam.config,
                flash_sync_pulse=flash_sync_pulse,
                audio_clap_cue=audio_clap_cue,
            )
            ws = self._ws_clients.get(cam.device_id)
            if ws is not None:
                try:
                    await ws.send_text(cmd.model_dump_json())
                    cam.state = CameraConnectionState.RECORDING
                    dispatched.append(cam.device_id)
                except Exception as exc:
                    errors[cam.device_id] = str(exc)
            else:
                errors[cam.device_id] = "No active WebSocket control channel"

        return {
            "session_id": session_id,
            "take_id": take_id,
            "scheduled_start_studio_ns": target_studio_ns,
            "dispatched_devices": dispatched,
            "errors": errors,
        }

    async def broadcast_stop_record(self, session_id: str, take_id: str) -> List[str]:
        cmd = StopRecordCommand(session_id=session_id, take_id=take_id)
        stopped: List[str] = []
        for did, ws in list(self._ws_clients.items()):
            try:
                await ws.send_text(cmd.model_dump_json())
                cam = self.camera_manager.get_camera(did)
                if cam is not None:
                    cam.state = CameraConnectionState.CONNECTED
                stopped.append(did)
            except Exception:
                pass
        return stopped

    def _build_app(self) -> FastAPI:
        app = FastAPI(title="Nuranova Mocap Studio Local Server", version="1.0.0")
        server = self

        def require_auth(
            authorization: Optional[str] = Header(default=None),
            x_device_id: Optional[str] = Header(default=None),
        ) -> ManagedCameraRecord:
            if not authorization or not authorization.startswith("Bearer "):
                raise HTTPException(status_code=401, detail="Missing Bearer authentication token.")
            token = authorization[len("Bearer ") :].strip()
            cam = server.camera_manager.authenticate_token(token, device_id=x_device_id)
            if cam is None:
                raise HTTPException(status_code=401, detail="Invalid or unpaired camera authentication token.")
            return cam

        @app.get("/api/v1/health")
        async def health():
            return {
                "status": "ok",
                "studio_name": server.studio_name,
                "protocol_version": PROTOCOL_VERSION,
                "connected_cameras": len(server.camera_manager.list_cameras()),
            }

        @app.post("/api/v1/pair", response_model=PairResponse)
        async def pair_device(req: PairRequest, request: Request):
            client_ip = request.client.host if request.client else ""
            try:
                return server.camera_manager.pair_device(req, ip_address=client_ip)
            except PermissionError as exc:
                raise HTTPException(status_code=403, detail=str(exc)) from exc
            except ValueError as exc:
                raise HTTPException(status_code=400, detail=str(exc)) from exc

        @app.get("/api/v1/cameras")
        async def list_cameras(cam: ManagedCameraRecord = Depends(require_auth)):
            return [c.model_dump() for c in server.camera_manager.list_summaries()]

        @app.post("/api/v1/sync/clock", response_model=ClockSyncResponse)
        async def sync_clock(req: ClockSyncRequest, cam: ManagedCameraRecord = Depends(require_auth)):
            t2 = time.monotonic_ns()
            if req.device_id != cam.device_id:
                raise HTTPException(status_code=403, detail="Device ID mismatch.")
            t3 = time.monotonic_ns()
            return ClockSyncResponse(
                device_id=req.device_id,
                seq=req.seq,
                client_t1_ns=req.client_t1_ns,
                server_t2_ns=t2,
                server_t3_ns=t3,
            )

        @app.post("/api/v1/sync/report")
        async def report_clock_sample(payload: Dict[str, Any], cam: ManagedCameraRecord = Depends(require_auth)):
            sample = ClockSyncSample(
                seq=int(payload["seq"]),
                t1_client_ns=int(payload["t1_client_ns"]),
                t2_server_ns=int(payload["t2_server_ns"]),
                t3_server_ns=int(payload["t3_server_ns"]),
                t4_client_ns=int(payload["t4_client_ns"]),
            )
            model = server.camera_manager.record_clock_sample(cam.device_id, sample)
            return {
                "camera_uid": cam.camera_uid,
                "residual_rmse_ms": model.residual_rmse_ms if model else None,
                "drift_ppm": model.drift_ppm if model else None,
                "meets_5ms_target": model.meets_5ms_target if model else False,
            }

        @app.post("/api/v1/telemetry")
        async def post_telemetry(tel: DeviceTelemetry, cam: ManagedCameraRecord = Depends(require_auth)):
            if tel.device_id != cam.device_id:
                raise HTTPException(status_code=403, detail="Device ID mismatch.")
            server.camera_manager.update_telemetry(tel)
            return {"ok": True}

        @app.post("/api/v1/transfers/init", response_model=TransferInitResponse)
        async def init_transfer(req: TransferInitRequest, cam: ManagedCameraRecord = Depends(require_auth)):
            if req.device_id != cam.device_id:
                raise HTTPException(status_code=403, detail="Device ID mismatch.")
            safe_take = "".join(ch for ch in req.take_id if ch.isalnum() or ch in ("_", "-"))
            if not safe_take:
                raise HTTPException(status_code=400, detail="Invalid take_id.")

            key = (req.device_id, safe_take, req.filename)
            if key in server._transfer_lookup:
                tid = server._transfer_lookup[key]
                slot = server._transfers[tid]
                existing_size = slot.dest_path.stat().st_size if slot.dest_path.exists() else 0
                slot.received_bytes = existing_size
                return TransferInitResponse(
                    transfer_id=tid,
                    received_bytes=existing_size,
                    already_complete=(existing_size == slot.total_size_bytes and slot.verified),
                )

            sub = "timestamps" if req.file_kind == "timestamps" else "recordings"
            dest_dir = server.storage_root / sub / safe_take
            dest_dir.mkdir(parents=True, exist_ok=True)
            dest_path = (dest_dir / f"{cam.camera_uid}_{req.filename}").resolve()
            if not str(dest_path).startswith(str(server.storage_root.resolve())):
                raise HTTPException(status_code=400, detail="Path escape blocked.")

            tid = uuid.uuid4().hex
            existing_size = dest_path.stat().st_size if dest_path.exists() else 0
            slot = TransferSlot(
                transfer_id=tid,
                device_id=req.device_id,
                session_id=req.session_id,
                take_id=safe_take,
                file_kind=req.file_kind,
                dest_path=dest_path,
                total_size_bytes=req.total_size_bytes,
                expected_sha256=req.sha256_hex.lower(),
                received_bytes=existing_size,
            )
            server._transfers[tid] = slot
            server._transfer_lookup[key] = tid
            cam.state = CameraConnectionState.TRANSFERRING
            return TransferInitResponse(transfer_id=tid, received_bytes=existing_size, already_complete=False)

        @app.put("/api/v1/transfers/{transfer_id}/chunk")
        async def upload_chunk(
            transfer_id: str,
            request: Request,
            x_chunk_offset: int = Header(..., alias="X-Chunk-Offset"),
            cam: ManagedCameraRecord = Depends(require_auth),
        ):
            slot = server._transfers.get(transfer_id)
            if slot is None or slot.device_id != cam.device_id:
                raise HTTPException(status_code=404, detail="Transfer session not found.")
            data = await request.body()
            if x_chunk_offset < 0 or x_chunk_offset > slot.total_size_bytes:
                raise HTTPException(status_code=400, detail="Invalid chunk offset.")

            mode = "r+b" if slot.dest_path.exists() else "wb"
            with slot.dest_path.open(mode) as f:
                f.seek(x_chunk_offset)
                f.write(data)
            slot.received_bytes = slot.dest_path.stat().st_size
            return {"transfer_id": transfer_id, "received_bytes": slot.received_bytes}

        @app.post("/api/v1/transfers/{transfer_id}/finalize", response_model=TransferStatusResponse)
        async def finalize_transfer(transfer_id: str, cam: ManagedCameraRecord = Depends(require_auth)):
            slot = server._transfers.get(transfer_id)
            if slot is None or slot.device_id != cam.device_id:
                raise HTTPException(status_code=404, detail="Transfer session not found.")
            if not slot.dest_path.exists():
                raise HTTPException(status_code=400, detail="Uploaded file missing.")

            h = hashlib.sha256()
            with slot.dest_path.open("rb") as f:
                for chunk in iter(lambda: f.read(1024 * 1024), b""):
                    h.update(chunk)
            computed = h.hexdigest().lower()
            slot.computed_sha256 = computed
            slot.received_bytes = slot.dest_path.stat().st_size
            slot.verified = (computed == slot.expected_sha256) and (slot.received_bytes == slot.total_size_bytes)
            cam.state = CameraConnectionState.CONNECTED
            return TransferStatusResponse(
                transfer_id=transfer_id,
                received_bytes=slot.received_bytes,
                total_size_bytes=slot.total_size_bytes,
                verified=slot.verified,
                computed_sha256=computed,
                expected_sha256=slot.expected_sha256,
                can_delete_local_copy=slot.verified,
            )

        @app.websocket("/ws/v1/camera/{device_id}")
        async def camera_websocket(websocket: WebSocket, device_id: str):
            token = websocket.query_params.get("token", "")
            auth_hdr = websocket.headers.get("authorization", "")
            if not token and auth_hdr.startswith("Bearer "):
                token = auth_hdr[len("Bearer ") :].strip()
            cam = server.camera_manager.authenticate_token(token, device_id=device_id)
            if cam is None:
                await websocket.close(code=4401)
                return

            await websocket.accept()
            server._ws_clients[device_id] = websocket
            cam.state = CameraConnectionState.CONNECTED
            try:
                while True:
                    msg = await websocket.receive()
                    if msg.get("type") == "websocket.disconnect":
                        break
                    if msg.get("bytes") is not None:
                        server.camera_manager.update_preview_frame(device_id, msg["bytes"])
                    elif msg.get("text") is not None:
                        data = json.loads(msg["text"])
                        kind = data.get("type")
                        if kind == "ping_sync":
                            t2 = time.monotonic_ns()
                            await websocket.send_text(
                                json.dumps({
                                    "type": "pong_sync",
                                    "seq": data.get("seq", 0),
                                    "client_t1_ns": data.get("client_t1_ns", 0),
                                    "server_t2_ns": t2,
                                    "server_t3_ns": time.monotonic_ns(),
                                })
                            )
                        elif kind == "telemetry":
                            tel = DeviceTelemetry(**data["payload"])
                            server.camera_manager.update_telemetry(tel)
            except WebSocketDisconnect:
                pass
            finally:
                server._ws_clients.pop(device_id, None)
                server.camera_manager.mark_disconnected(device_id)

        # Blender Bridge local endpoints (localhost / LAN read-only motion handoff)
        @app.get("/api/v1/bridge/status", response_model=BridgeStatusPayload)
        async def bridge_status():
            takes = [
                {"take_id": tid, "path": str(p), "exists": p.exists()}
                for tid, p in server.bridge_takes.items()
            ]
            latest = str(list(server.bridge_takes.values())[-1]) if server.bridge_takes else None
            return BridgeStatusPayload(
                active_project_name=server.bridge_project_name,
                active_project_path=server.bridge_project_path,
                available_takes=takes,
                latest_motion_file=latest,
            )

        @app.get("/api/v1/bridge/takes/{take_id}")
        async def bridge_get_take(take_id: str):
            p = server.bridge_takes.get(take_id)
            if p is None or not p.exists():
                raise HTTPException(status_code=404, detail=f"Take '{take_id}' not found for Blender bridge.")
            return JSONResponse(content=json.loads(p.read_text(encoding="utf-8")))

        return app
